// Generates the dotted world map used by GlobalPresence.astro from Natural Earth 110m land
// (public domain, scripts/data/ne_110m_land.geojson). Outputs:
//   src/assets/world/world-dots.svg   decorative land dots (loaded as <img>)
//   src/components/world-markers.css  marker positions as classes (no inline styles, CSP-safe)
//   src/data/world-markers.json       the same positions in map units, for the arcs
// Re-run only if the markers or projection change: node scripts/make-world-map.mjs
import { readFile, writeFile } from 'node:fs/promises';

const W = 1200;
const LAT_TOP = 83;
const LAT_BOTTOM = -58; // crop Antarctica
const H = Math.round((W * (LAT_TOP - LAT_BOTTOM)) / 360);
const STEP = 2.2; // degrees between dots

const MARKERS = {
  melbourne: [-37.81, 144.96],
  perth: [-31.95, 115.86],
  'middle-east': [25.2, 55.27],
  europe: [48.85, 2.35],
};

const project = ([lat, lon]) => [
  ((lon + 180) / 360) * W,
  ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * H,
];

const geo = JSON.parse(
  await readFile(new URL('./data/ne_110m_land.geojson', import.meta.url), 'utf8'),
);
const polygons = geo.features.flatMap((f) =>
  f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates,
);

// Ray casting on the outer ring minus holes.
function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const onLand = (lon, lat) =>
  polygons.some(
    ([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((h) => inRing(lon, lat, h)),
  );

let d = '';
let count = 0;
for (let lat = LAT_TOP - STEP / 2; lat > LAT_BOTTOM; lat -= STEP) {
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    if (!onLand(lon, lat)) continue;
    const [x, y] = project([lat, lon]);
    d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`;
    count++;
  }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}"><path d="${d}" stroke="#c3cdea" stroke-opacity=".32" stroke-width="3.4" stroke-linecap="round" fill="none"/></svg>\n`;
await writeFile(new URL('../src/assets/world/world-dots.svg', import.meta.url), svg);

const pct = (n, total) => `${((n / total) * 100).toFixed(2)}%`;
let css = `/* Generated by scripts/make-world-map.mjs. Do not edit by hand. */\n.world { aspect-ratio: ${W} / ${H}; }\n`;
for (const [id, ll] of Object.entries(MARKERS)) {
  const [x, y] = project(ll);
  css += `.marker-${id} { left: ${pct(x, W)}; top: ${pct(y, H)}; }\n`;
}
await writeFile(new URL('../src/components/world-markers.css', import.meta.url), css);
const json = {
  width: W,
  height: H,
  markers: Object.fromEntries(
    Object.entries(MARKERS).map(([id, ll]) => [id, project(ll).map((n) => +n.toFixed(1))]),
  ),
};
await writeFile(
  new URL('../src/data/world-markers.json', import.meta.url),
  JSON.stringify(json, null, 2) + '\n',
);
console.log(`world map: ${count} dots, ${W}x${H}, ${(svg.length / 1024).toFixed(1)} KB`);
console.log(css);
